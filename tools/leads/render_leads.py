"""Render leads/leads.json into leads/LEADS.md, the readable view of the lab's research leads.

LEADS.md is generated: edit leads.json and run this script; never edit LEADS.md by hand. Leads are grouped by status
(in the order idea, scoping, data-available, in-progress, done, dropped) and sorted by id inside each group. The output
depends only on leads.json: no date, clock or path goes into it, so the same input always gives the same bytes.

    python tools/leads/render_leads.py           # writes leads/LEADS.md
    python tools/leads/render_leads.py --check   # exit 1 when LEADS.md differs from a fresh render, 0 when it matches

It does not validate the register; run tools/leads/check_leads.py for that. Exit 2 on a usage or input problem
(missing file, invalid JSON, a lead that is not an object). Standard library only; no network.
"""
import argparse
import json
import sys
from pathlib import Path

STATUS_ORDER = ("idea", "scoping", "data-available", "in-progress", "done", "dropped")
TIER_ORDER = ("T0", "T1", "T2", "T3")
HEADER = """<!-- Generated by tools/leads/render_leads.py from leads/leads.json. Do not edit by hand. -->

# Research leads

A lead is an idea, question or source worth following that is not yet a task. Each one says how sure we are of it
(the tier of its best source), what data it needs and what that source permits, how any public sentence from it would be
grounded, and what it must not be used to claim. A lead becomes a `proposed` row on the lab's task board only when
someone writes that row; only a person sets a row `ready`. How to add, update or drop a lead: [README.md](README.md).

Tiers: T0 a summary or memory, unverified; T1 a quote from a primary source with its id and date; T2 T1 plus a script
check and a different model's check; T3 T2 plus a person's review. Effort is an estimate.
"""


class InputProblem(Exception):
    pass


def default_paths():
    root = Path(__file__).resolve().parents[2]
    return root / "leads" / "leads.json", root / "leads" / "LEADS.md"


def load(path):
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise InputProblem(f"leads file not found: {path}")
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        raise InputProblem(f"invalid JSON in leads file: {e}")
    if not isinstance(data, dict) or not isinstance(data.get("leads"), list):
        raise InputProblem("leads file must be an object with a 'leads' list")
    for lead in data["leads"]:
        if not isinstance(lead, dict):
            raise InputProblem("every lead must be an object")
    return data["leads"]


def cell(text):
    """Text safe inside a Markdown table cell: one line, pipes escaped."""
    return " ".join(str(text).split()).replace("|", "\\|")


def best_tier(lead):
    tiers = [s.get("tier") for s in lead.get("sources", []) if isinstance(s, dict) and s.get("tier") in TIER_ORDER]
    return max(tiers, key=TIER_ORDER.index) if tiers else "none"


def effort_text(lead):
    e = lead.get("effort")
    size = e.get("size", "?") if isinstance(e, dict) else "?"
    return f"{size} (estimate)"


def join(items, empty="none"):
    items = [str(i) for i in (items or [])]
    return ", ".join(items) if items else empty


def links_text(lead):
    links = lead.get("links") if isinstance(lead.get("links"), dict) else {}
    parts = []
    if links.get("board"):
        parts.append("board " + join(links["board"]))
    if links.get("prs"):
        parts.append("pull requests " + join(links["prs"]))
    if links.get("proposals"):
        parts.append("proposals " + join(links["proposals"]))
    return "; ".join(parts) if parts else "none"


def access_text(data):
    access = data.get("access")
    if isinstance(access, dict):
        return ", ".join(f"{k} {v}" for k, v in sorted(access.items()))
    ids = data.get("catalog_ids") or []
    return f"{join(ids)} ({access})" if ids else str(access)


def sort_key(lead):
    status = lead.get("status")
    rank = STATUS_ORDER.index(status) if status in STATUS_ORDER else len(STATUS_ORDER)
    return rank, str(lead.get("status")), str(lead.get("id"))


def render_lead(lead):
    data = lead.get("data_needed") if isinstance(lead.get("data_needed"), dict) else {}
    guard = lead.get("guard") if isinstance(lead.get("guard"), dict) else {}
    lines = [f"### {lead.get('id')} {lead.get('title')}", ""]
    lines.append(f"- **Question:** {lead.get('question')}")
    lines.append(f"- **Why it matters:** {lead.get('why_it_matters')}")
    lines.append("- **Sources:**")
    for s in lead.get("sources", []):
        if not isinstance(s, dict):
            continue
        read = f"read {s.get('read_on')}" if s.get("read_on") else "not read by us"
        if s.get("read_via"):
            read += f" ({s.get('read_via')})"
        note = f": {s.get('note')}" if s.get("note") else ""
        lines.append(f"  - {s.get('tier')}, {s.get('type')}, {read}. {s.get('ref')}{note}")
    have = "yes" if data.get("already_have") is True else "no"
    lines.append(f"- **Data:** {access_text(data)}; already have: {have}; fields missing: "
                 f"{join(data.get('fields_missing'))}")
    if data.get("not_in_catalog"):
        lines.append(f"- **Not in the catalog:** {join(data.get('not_in_catalog'))}")
    lines.append(f"- **Effort:** {effort_text(lead)}")
    lines.append(f"- **Guard:** {join(guard.get('ladder'))}. {guard.get('note', '')}".rstrip())
    lines.append("- **Must not claim:**")
    for m in lead.get("must_not_claim", []):
        lines.append(f"  - {m}")
    lines.append(f"- **Needs a person:** {join(lead.get('needs_person'))}")
    lines.append(f"- **Links:** {links_text(lead)}")
    creator = lead.get("created_by") if isinstance(lead.get("created_by"), dict) else {}
    who = creator.get("kind", "?") + (f" ({creator['model_id']})" if creator.get("model_id") else "")
    lines.append(f"- **Recorded:** created {lead.get('created')} by {who}; updated {lead.get('updated')}")
    if lead.get("notes"):
        lines.append(f"- **Notes:** {lead.get('notes')}")
    lines.append("")
    return lines


def render(leads):
    leads = sorted(leads, key=sort_key)
    counts = {}
    for lead in leads:
        counts[lead.get("status")] = counts.get(lead.get("status"), 0) + 1
    out = [HEADER]
    summary = ", ".join(f"{counts[s]} {s}" for s in STATUS_ORDER if s in counts)
    out.append(f"{len(leads)} leads: {summary}." if leads else "No leads yet.")
    out.append("")
    out.append("| Id | Title | Status | Best tier | Effort | Needs a person |")
    out.append("| --- | --- | --- | --- | --- | --- |")
    for lead in leads:
        out.append(f"| {cell(lead.get('id'))} | {cell(lead.get('title'))} | {cell(lead.get('status'))} | "
                   f"{best_tier(lead)} | {cell(effort_text(lead))} | {cell(join(lead.get('needs_person')))} |")
    out.append("")
    groups = []
    for lead in leads:
        if not groups or groups[-1][0] != lead.get("status"):
            groups.append((lead.get("status"), []))
        groups[-1][1].append(lead)
    for status, members in groups:
        out.append(f"## {str(status).capitalize()}")
        out.append("")
        for lead in members:
            out.extend(render_lead(lead))
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Render leads/leads.json into leads/LEADS.md.")
    ap.add_argument("--leads", help="path to leads.json (default: leads/leads.json in this repository)")
    ap.add_argument("--out", help="path to LEADS.md (default: leads/LEADS.md in this repository)")
    ap.add_argument("--check", action="store_true", help="exit 1 when the file differs from a fresh render; write nothing")
    try:
        args = ap.parse_args(argv)
    except SystemExit as e:
        return 0 if e.code == 0 else 2
    d_leads, d_out = default_paths()
    out_path = Path(args.out) if args.out else d_out
    try:
        text = render(load(Path(args.leads) if args.leads else d_leads))
    except InputProblem as e:
        print(f"error: {e}")
        return 2
    if args.check:
        try:
            # line endings are normalised, so a Windows checkout with CRLF endings still matches
            current = out_path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        except FileNotFoundError:
            print(f"{out_path.name} is missing; run tools/leads/render_leads.py")
            return 1
        if current != text:
            print(f"{out_path.name} is out of date; run tools/leads/render_leads.py")
            return 1
        print(f"{out_path.name} is up to date")
        return 0
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out_path.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
